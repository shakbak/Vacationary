CREATE TABLE IF NOT EXISTS stay_listings (
	city_key VARCHAR(128) NOT NULL,
	city_name VARCHAR(128) NOT NULL,
	name VARCHAR(255) NOT NULL,
	stay_type VARCHAR(32) NOT NULL,
	area VARCHAR(128) NOT NULL,
	price_per_night INT NOT NULL,
	rating DOUBLE PRECISION NOT NULL,
	url VARCHAR(1024) NOT NULL,
	sleeps INT NOT NULL,
	amenities VARCHAR(255) NOT NULL,
	PRIMARY KEY (city_key, name),
	CONSTRAINT stay_listings_price_chk CHECK (price_per_night >= 0),
	CONSTRAINT stay_listings_rating_chk CHECK (rating >= 0 AND rating <= 5),
	CONSTRAINT stay_listings_sleeps_chk CHECK (sleeps > 0)
);

CREATE TABLE IF NOT EXISTS conversations (
	channel VARCHAR(32) NOT NULL,
	external_user_id VARCHAR(255) NOT NULL,
	PRIMARY KEY (channel, external_user_id)
);

CREATE TABLE IF NOT EXISTS messages (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	channel VARCHAR(32) NOT NULL,
	external_user_id VARCHAR(255) NOT NULL,
	seq INT NOT NULL,
	role VARCHAR(32) NOT NULL,
	text TEXT NOT NULL,
	time TIMESTAMP WITH TIME ZONE NOT NULL,
	outcome_kind VARCHAR(32),
	UNIQUE (channel, external_user_id, seq),
	FOREIGN KEY (channel, external_user_id)
		REFERENCES conversations (channel, external_user_id) ON DELETE CASCADE,
	CONSTRAINT messages_seq_chk CHECK (seq >= 0),
	CONSTRAINT messages_outcome_role_chk CHECK (role = 'ASSISTANT' OR outcome_kind IS NULL)
);

CREATE TABLE IF NOT EXISTS stay_options (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	stay_type VARCHAR(32) NOT NULL,
	location VARCHAR(255) NOT NULL,
	price VARCHAR(64) NOT NULL,
	rating VARCHAR(32) NOT NULL,
	why TEXT NOT NULL,
	url VARCHAR(1024) NOT NULL
);

CREATE TABLE IF NOT EXISTS message_stay_options (
	message_id BIGINT NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
	seq INT NOT NULL,
	stay_option_id BIGINT NOT NULL UNIQUE REFERENCES stay_options (id) ON DELETE CASCADE,
	PRIMARY KEY (message_id, seq),
	CONSTRAINT message_stay_options_seq_chk CHECK (seq >= 0)
);

CREATE TABLE IF NOT EXISTS processed_events (
	channel VARCHAR(32) NOT NULL,
	event_id VARCHAR(255) NOT NULL,
	kind VARCHAR(32) NOT NULL,
	text TEXT NOT NULL,
	PRIMARY KEY (channel, event_id)
);

CREATE TABLE IF NOT EXISTS processed_event_stay_options (
	channel VARCHAR(32) NOT NULL,
	event_id VARCHAR(255) NOT NULL,
	seq INT NOT NULL,
	stay_option_id BIGINT NOT NULL UNIQUE REFERENCES stay_options (id) ON DELETE CASCADE,
	PRIMARY KEY (channel, event_id, seq),
	FOREIGN KEY (channel, event_id)
		REFERENCES processed_events (channel, event_id) ON DELETE CASCADE,
	CONSTRAINT processed_event_stay_options_seq_chk CHECK (seq >= 0)
);
